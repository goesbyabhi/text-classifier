"""
The request-time scorer: frozen embeddings in, calibrated probabilities out.

Math, kept deliberately small so it can be judged on eval numbers:
  - every text and every label is embedded once (Workers AI bge in the Worker,
    a feature-hash stand-in offline) and rows are L2-normalised;
  - a prototypical linear read: score(text, label) = cosine similarity between
    the text embedding and the label embedding;
  - single-label confidence is a temperature-scaled softmax over those scores;
  - multi-label is a per-label sigmoid over the same scores.

Both probabilities are calibrated: temperature/bias are fit on a holdout in
eval/ and shipped as a generated src/calibration.py module, imported at
request time (the Worker snapshot runs top-level code once at deploy, so an
import inside the loader is cheap). A calibration only applies when its
`embedder` matches the embedder that will actually score, so a hash-v0 fit
can never silently leak into the bge Worker. Until a matching calibration
exists the defaults are temperature=1.0, threshold 0.5: honest, just not
tuned.

numpy only, so it runs inside the Worker. Nothing here touches IO or the
runtime SDK.
"""

from __future__ import annotations

import json
import math

import numpy as np

DEFAULT_CALIBRATION = {
    # Softmax temperature over raw cosine scores (single-label).
    "temperature": 1.0,
    # Sigmoid shift then temperature for per-label multi-label probabilities.
    "multi_bias": 0.0,
    "multi_temperature": 1.0,
    # A label is returned when its calibrated probability crosses this.
    "multi_threshold": 0.5,
    # Provenance: the fit writes these so a number can be traced to a run.
    "fitted_on": None,
    "dataset": None,
    "embedder": None,
}


def load_calibration(path=None, embedder=None):
    """Read fitted calibration, falling back to defaults on any problem.

    Sources, in order:
      - a calibration dict passed straight through (Scorer callers);
      - src/calibration.py generated by scripts/train.py and bundled with the
        deploy (imported lazily so a missing module is just defaults);
      - a JSON file at `path` (kept for offline eval/bench runs).

    A calibration is only honored when its `embedder` matches the one that
    will actually score, so a fit made on the offline hash-v0 stand-in never
    applies to the bge Worker (pass embedder=<name> to enforce this).
    """
    if path is None and embedder is None:
        return dict(DEFAULT_CALIBRATION)
    if path is not None:
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError):
            return dict(DEFAULT_CALIBRATION)
    else:
        try:
            from calibration import CALIBRATION as data
        except (ImportError, AttributeError):
            return dict(DEFAULT_CALIBRATION)
    if embedder is not None and data.get("embedder") != embedder:
        return dict(DEFAULT_CALIBRATION)
    cal = dict(DEFAULT_CALIBRATION)
    cal.update({k: data[k] for k in cal if k in data})
    return cal


def normalise(rows: np.ndarray) -> np.ndarray:
    rows = np.asarray(rows, dtype=np.float32)
    norms = np.linalg.norm(rows, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    return rows / norms


def softmax_rows(z: np.ndarray) -> np.ndarray:
    z = z - z.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def sigmoid(z: np.ndarray) -> np.ndarray:
    # Clip before exp so far-off logits do not raise overflow warnings; the
    # result is indistinguishable within float precision afterwards.
    z = np.clip(np.asarray(z, dtype=np.float64), -30, 30)
    return 1.0 / (1.0 + np.exp(-z))


class Scorer:
    """Prototypical linear read over embeddings, with calibrated probabilities.

    Callers hand over already-computed embedding matrices (texts x d and
    labels x d); this class only does the linear read and the calibration, so
    the embedding source can be swapped (Workers AI in the Worker, feature
    hashing offline) without changing the math.
    """

    def __init__(self, calibration=None):
        cal = calibration if calibration is not None else load_calibration(None)
        cal = {**DEFAULT_CALIBRATION, **cal}
        self.temperature = float(cal["temperature"])
        self.multi_bias = float(cal["multi_bias"])
        self.multi_temperature = float(cal["multi_temperature"])
        self.multi_threshold = float(cal["multi_threshold"])

    def scores(self, text_embs, label_embs) -> np.ndarray:
        """Cosine similarity between every text and every label. (N x L)."""
        X = normalise(text_embs)
        L = normalise(label_embs)
        return X @ L.T

    def single_probs(self, text_embs, label_embs) -> np.ndarray:
        """Temperature-scaled softmax over the label scores. (N x L)."""
        return softmax_rows(self.scores(text_embs, label_embs) / self.temperature)

    def multi_probs(self, text_embs, label_embs) -> np.ndarray:
        """Independent per-label calibrated probabilities. (N x L)."""
        s = self.scores(text_embs, label_embs)
        return sigmoid((s - self.multi_bias) / self.multi_temperature)


# ---------------------------------------------------------------------------
# Calibration fitting. numpy-only on purpose: scripts/train.py runs on a plain
# laptop with the same numeric results as anything heavier.
# ---------------------------------------------------------------------------


def _single_nll(temperature, scores_all, true_idx) -> float:
    """Mean negative log-likelihood of the true labels under softmax(S/T).

    scores_all is (N x L), true_idx is (N,) giving the true label per row.
    Guarded against temperature <= 0 and overflow.
    """
    if temperature <= 0:
        return math.inf
    z = scores_all / temperature
    zmax = z.max(axis=1, keepdims=True)
    logsumexp = zmax.ravel() + np.log(np.exp(z - zmax).sum(axis=1))
    return float(np.mean(logsumexp - z[np.arange(z.shape[0]), true_idx]))


def _golden(fn, a, b, iters=60):
    """Golden-section minimisation of fn over [a, b]."""
    phi = (math.sqrt(5) - 1) / 2
    c = b - phi * (b - a)
    d = a + phi * (b - a)
    fc, fd = fn(c), fn(d)
    for _ in range(iters):
        if fc < fd:
            b, d, fd = d, c, fc
            c = b - phi * (b - a)
            fc = fn(c)
        else:
            a, c, fc = c, d, fd
            d = a + phi * (b - a)
            fd = fn(d)
    return (a + b) / 2


def fit_temperature(scores_all, true_idx, lo=0.1, hi=30.0):
    """Fit the single-label softmax temperature by NLL minimisation.

    Searches over log-temperature so the step is scale-free.
    """
    def nll(log_t):
        return _single_nll(math.exp(log_t), scores_all, true_idx)

    best = _golden(nll, math.log(lo), math.log(hi))
    temperature = math.exp(best)
    return temperature, _single_nll(temperature, scores_all, true_idx)


def _multi_bce(bias, temperature, s, y) -> float:
    if temperature <= 0:
        return math.inf
    p = sigmoid((s - bias) / temperature)
    p = np.clip(p, 1e-7, 1 - 1e-7)
    return float(np.mean(-(y * np.log(p) + (1 - y) * np.log(1 - p))))


def fit_multi(s, y):
    """Fit (bias, temperature) for the multi-label sigmoid by coordinate
    golden-section descent. s is (N x L) raw cosine scores, y is 0/1 labels.
    """

    def on_bias(bias):
        return _multi_bce(bias, temperature, s, y)

    def on_temp(log_t):
        return _multi_bce(bias, math.exp(log_t), s, y)

    bias = 0.0
    temperature = 1.0
    for _ in range(8):
        bias = _golden(on_bias, -2.0, 2.0)
        temperature = math.exp(_golden(on_temp, math.log(0.05), math.log(30.0)))
    return bias, temperature, _multi_bce(bias, temperature, s, y)


def fit_multi_threshold(s, y, bias, temperature):
    """Pick the sigmoid decision boundary that best separates in the fit data.

    The raw BCE fit moves the bias, which moves where probabilities land; a
    fixed threshold of 0.5 is then wrong (the first fitted model returned F1 0
    at 0.5 while scoring every label < 0.5). Search the observed probability
    mass with the F1 metric the caller actually cares about.
    """
    p = sigmoid((s - bias) / temperature)
    yb = y.astype(bool)
    lo, hi = float(p.min()), float(p.max())
    best_t, best_f1 = 0.5, -1.0
    for t in np.linspace(lo, hi, 100):
        pred = (p >= t).astype(bool)
        tp = float(np.sum(pred & yb))
        fp = float(np.sum(pred & ~yb))
        fn = float(np.sum(~pred & yb))
        f1 = 2 * tp / (2 * tp + fp + fn) if tp + fp + fn else 0.0
        if f1 >= best_f1:
            best_f1, best_t = f1, float(t)
    return best_t, best_f1