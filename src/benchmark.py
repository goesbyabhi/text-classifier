"""
The measured benchmark served at GET /benchmark.

Mirrors the reference's BENCHMARK document: a plain-text block of the numbers
eval actually measured. The convention in AGENTS.md is that measured numbers
are only ever sourced from eval/, never typed into docs by hand — so the bytes
served at /benchmark come from a *generated* module (benchmark_data.py, written
by scripts/train_bge.py from eval/results/eval-bge.json). If that module is
absent this falls back to an honest stub with no numbers in it.

Pure module: no `workers.*`, so pytest can drive it directly.
"""

from __future__ import annotations

import importlib

STUB = """text-classifier — measured benchmark
======================================

No measured benchmark is bundled with this build yet.

The Worker ships measured numbers as a generated module written by
scripts/train_bge.py from eval/results/eval-bge.json (never typed by hand).
Run that against eval/data/ and redeploy to populate this page. The API is
documented at /.
"""


def render(report: dict) -> str:
    """Format a train_bge eval report into the plain-text benchmark block."""
    cal = report.get("calibration") if isinstance(report.get("calibration"), dict) else {}
    n = report.get("n", 0)
    out = [
        "text-classifier — measured benchmark",
        "=" * 38,
        "",
        f"Measured on {report.get('date', '?')} with the frozen",
        f"{report.get('embedder', '?')} embedder against eval/data/",
        f"{report.get('dataset', '?')} ({n} records). These numbers come from",
        "eval/results/eval-bge.json — rerun scripts/train_bge.py to refresh.",
        "Measured numbers are never transcribed into docs by hand.",
    ]

    single = report.get("single_accuracy")
    rel = report.get("reliability")
    multi = report.get("multi_f1")
    if single is not None or rel is not None or multi is not None:
        out.append("")
        out.append("results")
        out.append("-------")
        if single is not None:
            out.append(f"  single-label accuracy   {single:.4f}")
        if rel is not None:
            out.append(f"  reliability (top>0.5)   {rel:.4f}")
        if multi is not None:
            thr = cal.get("multi_threshold")
            suffix = f" @ threshold {thr:.4f}" if thr is not None else ""
            out.append(f"  multi-label F1          {multi:.4f}{suffix}")

    cal_rows = [
        ("temperature", cal.get("temperature")),
        ("multi_bias", cal.get("multi_bias")),
        ("multi_temperature", cal.get("multi_temperature")),
        ("multi_threshold", cal.get("multi_threshold")),
    ]
    if any(v is not None for _, v in cal_rows):
        out.append("")
        out.append("calibration")
        out.append("-----------")
        for name, v in cal_rows:
            if v is not None:
                out.append(f"  {name:<18}{v:.4f}")
    out.append("")
    return "\n".join(out)


def get_benchmark() -> str:
    """The benchmark text to serve: generated bytes if present, else the stub."""
    try:
        return importlib.import_module("benchmark_data").BENCHMARK
    except Exception:  # noqa: BLE001 - module absent until train_bge.py runs
        return STUB