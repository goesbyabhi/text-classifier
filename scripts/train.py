"""
Fit the calibration shipped as src/calibration.py.

Runs locally on a plain laptop (no Workers runtime, no network needed if the
data is pre-embedded). Reads a labeled dataset, computes the same cosine
scores the Worker will, and fits the temperature/bias numbers that make the
reported confidence honest.

Input format (JSONL, one record per line):
    {"text": "...", "label": "spam"}              single-label
    {"text": "...", "labels": ["a", "b"]}         multi-label

Output: src/calibration.py, a tiny module containing one CALIBRATION dict. The
Worker bundles Python modules (not arbitrary files), so the generated module is
what ships; it carries an `embedder` key and is only honored when that matches
the embedder actually scoring, so an offline hash-v0 fit can never leak into
the bge Worker. The file is gitignored; the worker runs with
DEFAULT_CALIBRATION until this has been run and the module deployed.

Usage:
    uv run python scripts/train.py eval/data/calibration.jsonl \\
        --out src/calibration.py --embedder hash-v0
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import numpy as np

import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from classifier import DEFAULT_CALIBRATION, Scorer, fit_multi, fit_multi_threshold, fit_temperature  # noqa: E402
from embeddings import HashEmbedder  # noqa: E402


def load_records(path: Path):
    records = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def label_set(records):
    labels = []
    for r in records:
        ls = r.get("labels") if r.get("labels") else ([r["label"]] if r.get("label") else [])
        for l in ls:
            if l not in labels:
                labels.append(l)
    return labels


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset", type=Path, help="JSONL of labeled records")
    ap.add_argument("--out", type=Path, default=Path("src/calibration.py"))
    ap.add_argument("--embedder", default="hash-v0", choices=["hash-v0"])
    args = ap.parse_args()

    records = load_records(args.dataset)
    labels = label_set(records)
    print(f"loaded {len(records)} records, {len(labels)} labels")

    embedder = HashEmbedder()
    label_embs = embedder.embed_texts(labels)
    texts = [r["text"] for r in records]
    text_embs = embedder.embed_texts(texts)
    scorer = Scorer()  # raw cosine scores, defaults
    scores = scorer.scores(text_embs, label_embs)

    # Single-label NLL fit on the true label of each record.
    single_rows = [i for i, r in enumerate(records) if r.get("label")]
    if single_rows:
        ts = scores[np.array(single_rows)]
        true_idx = np.array([labels.index(records[i]["label"]) for i in single_rows])
        temperature, nll = fit_temperature(ts, true_idx)
        print(f"single-label: temperature={temperature:.4f} nll={nll:.4f} n={len(single_rows)}")
    else:
        temperature = DEFAULT_CALIBRATION["temperature"]
        nll = None

    # Multi-label BCE fit on the label sets of each record.
    multi_rows = [i for i, r in enumerate(records) if r.get("labels")]
    if multi_rows:
        y = np.zeros((len(multi_rows), len(labels)), dtype=float)
        for k, i in enumerate(multi_rows):
            for l in records[i]["labels"]:
                y[k, labels.index(l)] = 1.0
        bias, mtemp, bce = fit_multi(scores[np.array(multi_rows)], y)
        threshold, f1 = fit_multi_threshold(scores[np.array(multi_rows)], y, bias, mtemp)
        print(f"multi-label: bias={bias:.4f} temperature={mtemp:.4f} threshold={threshold:.4f} bce={bce:.4f} f1={f1:.4f} n={len(multi_rows)}")
    else:
        bias = DEFAULT_CALIBRATION["multi_bias"]
        mtemp = DEFAULT_CALIBRATION["multi_temperature"]
        threshold = DEFAULT_CALIBRATION["multi_threshold"]
        bce = None
        f1 = None

    cal = {
        "temperature": round(temperature, 4),
        "multi_bias": round(bias, 4),
        "multi_temperature": round(mtemp, 4),
        "multi_threshold": round(threshold, 4),
        "fitted_on": date.today().isoformat(),
        "dataset": args.dataset.name,
        "embedder": args.embedder,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    _write_module(args.out, cal)
    print(f"wrote {args.out}")


def _write_module(path: Path, cal):
    """Emit a bundled calibration module (the Worker ships Python modules)."""
    body = "\n".join(f'    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},' for k, v in cal.items())
    path.write_text(
        '"""Generated by scripts/train.py — do not edit by hand."""\n\n'
        "CALIBRATION = {\n"
        f"{body}\n"
        "}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()